// Package caddy renders Guard's Caddyfile and loads it through Caddy's
// admin API.
package caddy

import (
	"fmt"
	"sort"
	"strings"

	"github.com/n04b/guard/internal/config"
	"github.com/n04b/guard/internal/rauthy"
)

// AdminAddr is where Caddy's admin API listens (loopback only).
const AdminAddr = "localhost:2019"

// Paths served by Guard itself.
const (
	CACertPath = "/.guard/ca.crt"
	HealthPath = "/health"
)

// Input is everything the Caddyfile depends on.
type Input struct {
	Cfg *config.Config
	// Mode is the resolved TLS mode (never auto).
	Mode config.TLSMode
	// FallbackDomains use the local CA because ACME failed and
	// tls.acme.allow_fallback is set.
	FallbackDomains map[string]bool
	// CADir contains root.crt of Caddy's local CA.
	CADir string
	// HealthAddr is guard-sync's health listener, e.g. 127.0.0.1:9100.
	HealthAddr string
}

// Render returns the Caddyfile for the configuration.
func Render(in Input) string {
	w := &writer{}
	c := in.Cfg
	s := c.Server.Server

	w.line("# Generated by guard-sync. Do not edit: it is rebuilt from /config/*.yml.")
	w.open("")
	w.line("admin %s", AdminAddr)
	// Inside the container Caddy always listens on 80/443. server.http_port
	// and server.https_port are the public ports browsers use (docker -p).
	// The local CA root is handed out explicitly; never touch the
	// container's trust store.
	w.line("skip_install_trust")
	switch in.Mode {
	case config.TLSACME:
		w.line("email %s", quote(c.TLS.TLS.ACME.Email))
		if c.TLS.TLS.ACME.CA != "" {
			w.line("acme_ca %s", quote(c.TLS.TLS.ACME.CA))
		}
	case config.TLSLocalCA:
		w.line("local_certs")
	}
	if len(s.TrustedProxies) > 0 {
		w.open("servers")
		w.line("trusted_proxies static %s", strings.Join(s.TrustedProxies, " "))
		w.close()
	}
	w.open("log")
	w.line("output stdout")
	w.line("format console")
	w.line("level INFO")
	w.close()
	w.close()

	usesLocalCA := in.Mode == config.TLSLocalCA || len(in.FallbackDomains) > 0
	allow := strings.Join(c.Server.Admin.AllowFrom, " ")
	rauthyUp := strings.TrimPrefix(rauthy.InternalURL(), "http://")

	// ---------- auth host ----------
	w.blank()
	w.open(s.Hostname)
	writeSiteCommon(w, in, s.Hostname)
	w.open("@admin_ui")
	w.line("path /auth/v1/admin /auth/v1/admin/*")
	w.line("not client_ip %s", allow)
	w.close()
	w.open("@health_detail")
	w.line("path %s", HealthPath)
	w.line("client_ip %s", allow)
	w.close()
	w.open("route")
	w.open("handle @admin_ui")
	w.line(`respond "Admin UI is only reachable from admin.allow_from" 403`)
	w.close()
	w.open("handle @health_detail")
	w.line("rewrite * /health/detail")
	w.line("reverse_proxy %s", in.HealthAddr)
	w.close()
	w.open("handle %s", HealthPath)
	w.line("rewrite * /health/public")
	w.line("reverse_proxy %s", in.HealthAddr)
	w.close()
	if usesLocalCA {
		writeCAHandler(w, in.CADir)
	}
	w.open("handle")
	w.line("reverse_proxy %s", rauthyUp)
	w.close()
	w.close() // route
	w.close() // site

	// Plain-HTTP sites. Caddy redirects to HTTPS on its own, but only to
	// port 443; with another public port Guard writes the redirects itself.
	customRedirect := s.HTTPSPort != 443
	if usesLocalCA {
		// Allow downloading the root certificate over plain HTTP before
		// it is trusted; everything else is redirected to HTTPS.
		w.blank()
		w.open("http://" + s.Hostname)
		w.open("route")
		writeCAHandler(w, in.CADir)
		w.open("handle")
		w.line("redir https://%s{uri} 308", c.PublicHost())
		w.close()
		w.close()
		w.close()
	}
	if customRedirect {
		var hosts []string
		if !usesLocalCA {
			hosts = append(hosts, "http://"+s.Hostname)
		}
		for _, a := range c.Applications {
			hosts = append(hosts, "http://"+a.Domain)
		}
		sort.Strings(hosts)
		w.blank()
		w.open(strings.Join(hosts, ", "))
		w.line("redir https://{host}:%d{uri} 308", s.HTTPSPort)
		w.close()
	}

	// ---------- applications ----------
	apps := make([]*config.Application, 0, len(c.Applications))
	for i := range c.Applications {
		apps = append(apps, &c.Applications[i])
	}
	sort.Slice(apps, func(i, j int) bool { return apps[i].Domain < apps[j].Domain })

	for _, a := range apps {
		w.blank()
		w.line("# %s (%s, auth: %s)", a.Name, a.File, a.Auth.Mode)
		w.open(a.Domain)
		writeSiteCommon(w, in, a.Domain)
		w.open("route")
		// Identity headers only ever come from Guard.
		for _, h := range rauthy.AuthHeaderNames() {
			w.line("request_header -%s", h)
		}
		if a.Auth.Mode == config.ModeProxy {
			id := a.Auth.ClientID
			w.open("handle %s", config.ForwardAuthCallbackPath)
			w.line("rewrite * /auth/v1/clients/%s/forward_auth/callback?{query}", id)
			w.line("reverse_proxy %s", rauthyUp)
			w.close()
			w.open("handle %s", config.ForwardAuthLogoutPath)
			w.line("redir %s/auth/v1/oidc/logout 302", c.PublicURL())
			w.close()
			w.open("handle")
			w.open("forward_auth %s", rauthyUp)
			w.line("uri /auth/v1/clients/%s/forward_auth?redirect_state=302", id)
			w.line("copy_headers %s", strings.Join(rauthy.AuthHeaderNames(), " "))
			w.close()
			writeUpstream(w, a)
			w.close()
		} else {
			writeUpstream(w, a)
		}
		w.close() // route
		w.close() // site
	}
	return w.String()
}

func writeSiteCommon(w *writer, in Input, host string) {
	switch {
	case in.Mode == config.TLSCustom:
		t := in.Cfg.TLS.TLS.Custom
		w.line("tls %s %s", quote(t.Certificate), quote(t.PrivateKey))
	case in.Mode == config.TLSLocalCA || in.FallbackDomains[host]:
		w.line("tls internal")
	}
	w.open("header")
	w.line("-Server")
	if in.Mode == config.TLSCustom || (in.Mode == config.TLSACME && !in.FallbackDomains[host]) {
		w.line(`Strict-Transport-Security "max-age=31536000"`)
	}
	w.line(`X-Content-Type-Options "nosniff"`)
	w.line(`Referrer-Policy "strict-origin-when-cross-origin"`)
	w.close()
}

func writeCAHandler(w *writer, caDir string) {
	w.open("handle %s", CACertPath)
	w.line("root * %s", quote(caDir))
	w.line("rewrite * /root.crt")
	w.line("header Content-Type application/x-x509-ca-cert")
	w.line(`header Content-Disposition "attachment; filename=guard-root-ca.crt"`)
	w.line("file_server")
	w.close()
}

func writeUpstream(w *writer, a *config.Application) {
	u := a.Upstream
	target := fmt.Sprintf("%s://%s:%d", u.Scheme, u.Host, u.Port)
	if u.Scheme == "https" && u.TLSInsecureSkipVerify {
		w.open("reverse_proxy %s", target)
		w.open("transport http")
		w.line("tls_insecure_skip_verify")
		w.close()
		w.close()
		return
	}
	w.line("reverse_proxy %s", target)
}

// quote returns a Caddyfile token, quoted when needed.
func quote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\n\"'{}#\\`") {
		return s
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// ---------- writer ----------

type writer struct {
	b     strings.Builder
	depth int
}

func (w *writer) String() string { return w.b.String() }

func (w *writer) line(format string, args ...any) {
	w.b.WriteString(strings.Repeat("\t", w.depth))
	if len(args) == 0 {
		w.b.WriteString(format)
	} else {
		fmt.Fprintf(&w.b, format, args...)
	}
	w.b.WriteByte('\n')
}

func (w *writer) blank() { w.b.WriteByte('\n') }

func (w *writer) open(format string, args ...any) {
	if format == "" {
		w.line("{")
	} else {
		w.line(format+" {", args...)
	}
	w.depth++
}

func (w *writer) close() {
	w.depth--
	w.line("}")
}
