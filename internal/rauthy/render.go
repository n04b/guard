// Internal addresses inside the container. Rauthy and Hiqlite only listen
// on loopback; Caddy is the only way in.
const (
	ListenAddress = "127.0.0.1"
	ListenPort    = 8080
	RaftPort      = 8100
	HQLAPIPort    = 8200
)

// InternalURL is the base URL guard-sync and Caddy use to reach Rauthy.
func InternalURL() string { return fmt.Sprintf("http://%s:%d", ListenAddress, ListenPort) }

// Auth header names Rauthy adds to successful forward-auth responses.
// Caddy copies exactly these to the upstream request.
var AuthHeaders = map[string]string{
	"user":               "X-Guard-User",
	"email":              "X-Guard-Email",
	"email_verified":     "X-Guard-Email-Verified",
	"groups":             "X-Guard-Groups",
	"roles":              "X-Guard-Roles",
	"given_name":         "X-Guard-Given-Name",
	"family_name":        "X-Guard-Family-Name",
	"mfa":                "X-Guard-Mfa",
	"preferred_username": "X-Guard-Username",
}

// AuthHeaderNames returns the header names in a stable order.
func AuthHeaderNames() []string {
	return []string{
		"X-Guard-User", "X-Guard-Email", "X-Guard-Email-Verified", "X-Guard-Groups",
		"X-Guard-Roles", "X-Guard-Given-Name", "X-Guard-Family-Name", "X-Guard-Mfa",
		"X-Guard-Username",
	}
}

// RenderInput is everything needed to render Rauthy's config.toml.
type RenderInput struct {
	Cfg          *config.Config
	DataDir      string // Hiqlite data dir, e.g. /data/rauthy
	BootstrapDir string // directory with api_keys.json, e.g. /run/guard/rauthy/bootstrap
	EncKey       string // "<id>/<base64>"
	RaftSecret   string
	APISecret    string
	SMTPPassword string
}

// RenderConfig returns the content of Rauthy's config.toml. The result
// contains secrets and must be written with mode 0600.
func RenderConfig(in RenderInput) (string, error) {
	c := in.Cfg
	keyID, err := secrets.EncKeyID(in.EncKey)
	if err != nil {
		return "", err
	}
	s := c.Server
	sec := c.Security
	w := &tomlWriter{}

	w.comment("Generated by guard-sync. Do not edit: changes are overwritten on every start.")
	w.comment("Edit /config/guard.yml instead.")

	w.section("access")
	w.str("cookie_mode", "host")
	w.boolean("session_validate_ip", true)

	w.section("auth_headers")
	w.boolean("enable", true)
	w.boolean("enable_pref_username", true)
	// Non-ASCII names (e.g. Cyrillic) are percent-encoded so they survive
	// proxies. Downstream apps decode them as UTF-8.
	w.boolean("percent_encode", true)
	for _, k := range []string{"user", "roles", "groups", "email", "email_verified", "family_name", "given_name", "mfa", "preferred_username"} {
		w.str(k, strings.ToLower(AuthHeaders[k]))
	}

	w.section("bootstrap")
	w.str("admin_email", s.Admin.BootstrapEmail)
	w.str("bootstrap_dir", in.BootstrapDir)

	w.section("cluster")
	w.integer("node_id", 1)
	w.strs("nodes", []string{fmt.Sprintf("1 %s:%d %s:%d", ListenAddress, RaftPort, ListenAddress, HQLAPIPort)})
	w.str("listen_addr_api", ListenAddress)
	w.str("listen_addr_raft", ListenAddress)
	w.str("data_dir", in.DataDir)
	// Single node: flush the Raft log on every write.
	w.str("log_sync", "immediate_async")
	w.str("secret_raft", in.RaftSecret)
	w.str("secret_api", in.APISecret)
	w.str("backup_cron", s.Backup.Cron)
	w.str("backup_keep_for_local", fmt.Sprintf("%dd", s.Backup.KeepDays))

	w.section("database")
	w.boolean("hiqlite", true)

	w.section("email")
	w.str("rauthy_admin_email", s.Admin.BootstrapEmail)
	w.str("sub_prefix", s.WebAuthn.RPName)
	if s.SMTP.Enabled {
		w.str("smtp_url", s.SMTP.Host)
		w.integer("smtp_port", s.SMTP.Port)
		if s.SMTP.Username != "" {
			w.str("smtp_username", s.SMTP.Username)
		}
		if in.SMTPPassword != "" {
			w.str("smtp_password", in.SMTPPassword)
		}
		w.str("smtp_from", s.SMTP.From)
		mode := s.SMTP.TLSMode
		if mode == "plain" {
			mode = "danger-insecure"
		}
		w.str("smtp_tls_mode", mode)
	}

	w.section("encryption")
	w.strs("keys", []string{in.EncKey})
	w.str("key_active", keyID)

	w.section("events")
	w.str("email", s.Admin.BootstrapEmail)
	// No outgoing calls to GitHub for update checks.
	w.boolean("disable_app_version_check", true)
	if !s.SMTP.Enabled {
		w.str("notify_level_email", "critical")
	}

	w.section("hashing")
	w.integer("argon2_m_cost", sec.Hashing.MemoryMiB*1024)
	w.integer("argon2_t_cost", sec.Hashing.Iterations)
	w.integer("argon2_p_cost", sec.Hashing.Parallelism)
	w.integer("max_hash_threads", sec.Hashing.MaxParallelHashes)

	w.section("lifetimes")
	w.str("session_lifetime", fmt.Sprintf("%dh", sec.Session.MaxHours))
	w.str("session_timeout", fmt.Sprintf("%dm", sec.Session.IdleMinutes))

	w.section("logging")
	w.str("level", s.Logging.Level)
	w.str("level_database", "warn")
	w.str("level_access", "modifying")
	w.str("log_fmt", "text")

	w.section("mfa")
	w.boolean("admin_force_mfa", *s.Admin.RequirePasskey)

	w.section("server")
	w.str("listen_address", ListenAddress)
	w.integer("port_http", ListenPort)
	w.str("scheme", "http")
	w.str("pub_url", c.PublicHost())
	w.boolean("proxy_mode", true)
	w.strs("trusted_proxies", []string{"127.0.0.1/32", "::1/128"})
	w.boolean("metrics_enable", false)
	w.boolean("swagger_ui_enable", false)

	w.section("user_registration")
	w.boolean("enable", sec.Registration.Mode == config.RegistrationOpen)
	if d := sec.Registration.AllowedEmailDomain; d != "" {
		w.str("domain_restriction", strings.ToLower(d))
	}

	w.section("webauthn")
	w.str("rp_id", s.WebAuthn.RPID)
	w.str("rp_origin", c.PublicURL()+portSuffixForOrigin(c))
	w.str("rp_name", s.WebAuthn.RPName)
	// Always require user verification (biometrics / PIN).
	w.boolean("force_uv", true)

	return w.String(), nil
}

// portSuffixForOrigin: Rauthy wants the port in rp_origin. PublicURL()
// omits :443, so add it explicitly.
func portSuffixForOrigin(c *config.Config) string {
	if c.Server.Server.HTTPSPort == 443 {
		return ":443"
	}
	return ""
}

// apiKeyAccess lists the rights guard-sync needs.
var apiKeyAccess = []map[string]any{
	{"group": "Clients", "access_rights": []string{"read", "create", "update", "delete"}},
	{"group": "Groups", "access_rights": []string{"read", "create"}},
	{"group": "Roles", "access_rights": []string{"read", "create"}},
	{"group": "Secrets", "access_rights": []string{"read", "update"}},
	{"group": "Users", "access_rights": []string{"read", "create", "update"}},
}

// RenderAPIKeysJSON returns Rauthy's bootstrap api_keys.json for the
// guard-sync API key. apiKey has the form "<name>$<secret>".
func RenderAPIKeysJSON(apiKey string) ([]byte, error) {
	name, secret, ok := strings.Cut(apiKey, "$")
	if !ok || name != secrets.APIKeyName || len(secret) < 64 {
		return nil, fmt.Errorf("malformed API key secret")
	}
	keys := []map[string]any{{
		"name":   name,
		"secret": map[string]string{"Plain": secret},
		"access": apiKeyAccess,
	}}
	return json.MarshalIndent(keys, "", "  ")
}

// NewAPIKey generates "<name>$<secret>" for guard-sync.
func NewAPIKey() (string, error) {
	s, err := secrets.Alnum(64)
	if err != nil {
		return "", err
	}
	return secrets.APIKeyName + "$" + s, nil
}

// ---------- tiny TOML writer ----------

type tomlWriter struct{ b strings.Builder }

func (w *tomlWriter) String() string { return w.b.String() }

func (w *tomlWriter) comment(s string) { fmt.Fprintf(&w.b, "# %s\n", s) }

func (w *tomlWriter) section(name string) { fmt.Fprintf(&w.b, "\n[%s]\n", name) }

func (w *tomlWriter) str(k, v string) { fmt.Fprintf(&w.b, "%s = %s\n", k, tomlString(v)) }

func (w *tomlWriter) integer(k string, v int) { fmt.Fprintf(&w.b, "%s = %d\n", k, v) }

func (w *tomlWriter) boolean(k string, v bool) { fmt.Fprintf(&w.b, "%s = %t\n", k, v) }

func (w *tomlWriter) strs(k string, vs []string) {
	q := make([]string, len(vs))
	for i, v := range vs {
		q[i] = tomlString(v)
	}
	fmt.Fprintf(&w.b, "%s = [%s]\n", k, strings.Join(q, ", "))
}

// tomlString returns a TOML basic string with all required escapes.
func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if unicode.IsControl(r) {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
